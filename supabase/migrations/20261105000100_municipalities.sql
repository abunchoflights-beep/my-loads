alter table public.municipalities enable row level security;
revoke all on public.municipalities from anon, authenticated;
grant select on public.municipalities to anon, authenticated;

create policy municipalities_read_all on public.municipalities
  for select to anon, authenticated using (true);

-- -----------------------------------------------------------------------------
-- Search. Short queries return nothing instead of the whole table. The query
-- is normalized to [a-z0-9 ] first, so it can't smuggle LIKE wildcards.
-- -----------------------------------------------------------------------------
create or replace function public.search_municipalities(p_query text, p_limit integer default 20)
returns setof public.municipalities
language sql
stable
security invoker
set search_path = ''
as $$
  with q as (select private.normalize_search(p_query) as term)
  select m.*
    from public.municipalities m, q
   where char_length(q.term) >= 2
     and m.search_name like '%' || q.term || '%'
   order by
     case
       when m.search_name = q.term then 0
       when m.search_name like q.term || '%' then 1
       when m.search_name like '% ' || q.term || '%' then 2
       else 3
     end,
     m.name,
     m.code
   limit least(greatest(coalesce(p_limit, 20), 1), 50);
$$;

-- Signed-in only, like the route that calls it (anti-scraping, SECURITY §1).
grant execute on function public.search_municipalities(text, integer) to authenticated;

