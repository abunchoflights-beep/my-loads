-- Lower-case ASCII with accents and punctuation removed: "Apartadó" and
-- "APARTADO" both become "apartado". translate() runs before lower() so the
-- result doesn't depend on the database's locale.
create or replace function private.normalize_search(p_text text)
returns text
language sql
immutable
parallel safe
set search_path = ''
as $$
  select btrim(regexp_replace(
    lower(translate(coalesce(p_text, ''),
      'ÁÀÄÂÃáàäâãÉÈËÊéèëêÍÌÏÎíìïîÓÒÖÔÕóòöôõÚÙÜÛúùüûÑñÇç',
      'AAAAAaaaaaEEEEeeeeIIIIiiiiOOOOOoooooUUUUuuuuNnCc')),
    '[^a-z0-9]+', ' ', 'g'));
$$;

